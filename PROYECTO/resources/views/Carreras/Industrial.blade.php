<h1>Ingeniería en Industrial</h1>

  <p>La educación superior en el país exige un mayor esfuerzo en la formación de profesionales que sean capaces de responder a las necesidades actuales de la sociedad, debido a los cambios y los procesos de acreditación que se han venido ejecutando en las IES del Ecuador.

    La Carrera de Ingeniería Industrial se orienta en optimizar procesos, ahorrar recursos en las organizaciones de productos o servicios, además estudia la  seguridad industrial, calidad para ofrecer un profesional íntegro, en varias disciplinas de la ingeniería, con conocimientos, habilidades, aptitudes y actitudes, herramientas necesarias para su formación académica, laboral y personal.</p>

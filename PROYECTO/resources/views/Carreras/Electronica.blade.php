<h1>Ingeniería en Electricidad</h1>

  <p>Bienvenidos a la carrera de Electricidad

    La ingeniería, en general, es el conjunto de conocimientos científicos y tecnológicos orientados a la innovación, invención, desarrollo y mejora de técnicas que conducen a la solución de problemas de la sociedad. En particular, la Carrera de Electricidad se enfoca en el estudio de la generación, manejo de los sistemas de transporte y distribución de la energía eléctrica. La electricidad se encuentra presente en todos los ámbitos de la vida moderna, desde su uso en los hogares hasta su aplicación en la industria, las telecomunicaciones, medicina, internet, espacios de recreación, etc. Por lo que, la Ingeniería Eléctrica es una de las profesiones de gran demanda en el mercado laboral, pues la sociedad actual no se concibe sin la generación de electricidad y sus usos múltiples.

    El Ingeniero Eléctrico es un profesional, que puede desempeñarse en empresas públicas, privadas, docencia, centros de investigación y desarrollo o en libre ejercicio de la profesión, teniendo un amplio campo de acción, desarrollando los siguientes roles: planificador de proyectos, diseñador, constructor y operador de proyectos eléctricos, consultor, supervisor y fiscalizador de proyectos eléctricos.

    La Carrera de Electricidad, tiene como objetivo formar profesionales críticos, creativos, capacitados, humanistas y éticos, con alto dominio de los fundamentos científicos metodológicos inherentes al sector ingenieril eléctrico y el campo técnico industrial, promoviendo la responsabilidad, el liderazgo y el trabajo en equipo, para así contribuir al desarrollo industrial, económico, científico y educativo de la zona y del país.</p>
